import { NextRequest, NextResponse } from 'next/server'
import { requireAuth } from '@/lib/auth-helper'
import Anthropic from '@anthropic-ai/sdk'

export const runtime = 'nodejs'
export const maxDuration = 60

const DISCLAIMER = 'DISCLAIMER: This document was generated by Saguaro Construction Intelligence Platform. This document does not constitute legal advice. Verify compliance with current state statutes and consult a licensed state construction attorney before relying on this document for legal purposes.'

const VALID_TYPES = ['ntp', 'substantial_completion', 'final_completion', 'punch_list', 'retainage_release'] as const
type LetterType = typeof VALID_TYPES[number]

const LETTER_CONFIGS: Record<LetterType, { title: string; description: string; issuedTo: string }> = {
  ntp: { title: 'Notice to Proceed', description: 'Authorizes the contractor to begin work', issuedTo: 'contractor' },
  substantial_completion: { title: 'Certificate of Substantial Completion', description: 'Certifies substantial completion per contract', issuedTo: 'owner' },
  final_completion: { title: 'Certificate of Final Completion', description: 'Certifies final completion and acceptance', issuedTo: 'owner' },
  punch_list: { title: 'Punch List Transmittal Letter', description: 'Transmits the final punch list to the contractor', issuedTo: 'contractor' },
  retainage_release: { title: 'Retainage Release Authorization', description: 'Authorizes release of retained funds upon final completion', issuedTo: 'contractor' },
}

export async function POST(req: NextRequest) {
  const auth = await requireAuth()
  if (auth instanceof NextResponse) return auth
  const { supabase, tenantId } = auth
  const { projectId, letterType, effectiveDate, additionalNotes } = await req.json()

  if (!projectId || !letterType) {
    return NextResponse.json({ error: 'projectId and letterType required' }, { status: 400 })
  }
  if (!VALID_TYPES.includes(letterType)) {
    return NextResponse.json(
      { error: `Invalid letterType. Must be one of: ${VALID_TYPES.join(', ')}` },
      { status: 400 },
    )
  }

  const typed = letterType as LetterType
  const config = LETTER_CONFIGS[typed]

  const [{ data: project }, { data: gc }, { data: primeContract }] = await Promise.all([
    supabase.from('projects').select('*').eq('tenant_id', tenantId).eq('id', projectId).single(),
    supabase.from('tenant_settings').select('*').eq('tenant_id', tenantId).maybeSingle(),
    supabase
      .from('prime_contracts')
      .select('*')
      .eq('project_id', projectId)
      .eq('tenant_id', tenantId)
      .maybeSingle(),
  ])

  const today = new Date().toLocaleDateString('en-US', { year: 'numeric', month: 'long', day: 'numeric' })
  const effectiveDateStr = effectiveDate
    ? new Date(effectiveDate).toLocaleDateString('en-US', { year: 'numeric', month: 'long', day: 'numeric' })
    : today
  const gcName = gc?.company_name || 'General Contractor'
  const gcAddr = gc?.company_address
    ? `${gc.company_address}, ${gc.company_city || ''}, ${gc.company_state || ''} ${gc.company_zip || ''}`.trim()
    : ''
  const ownerName = project?.owner_name || primeContract?.owner_name || 'Owner'
  const contractNo = primeContract?.contract_number || project?.project_number || '—'
  const contractValue = Number(primeContract?.original_contract_value || project?.contract_value || 0)
  const retainagePct = Number(project?.retainage_pct || 10)
  const retainageHeld =
    Number(primeContract?.total_retainage_held || 0) ||
    Math.round((contractValue * retainagePct) / 100)

  let letterBody = ''
  try {
    const client = new Anthropic()
    const msg = await client.messages.create({
      model: 'claude-sonnet-4-20250514',
      max_tokens: 1200,
      messages: [{
        role: 'user',
        content: `Write a professional ${config.title} letter for a construction project.

FROM: ${gcName}
TO: ${typed === 'ntp' || typed === 'punch_list' ? ownerName + ' (issuing to contractor)' : ownerName}
PROJECT: ${project?.name || 'Project'}
ADDRESS: ${[project?.address, project?.city ? `${project.city}, ${project.state}` : ''].filter(Boolean).join(', ')}
CONTRACT NO: ${contractNo}
CONTRACT VALUE: $${contractValue.toLocaleString()}
EFFECTIVE DATE: ${effectiveDateStr}
${typed === 'retainage_release' ? `RETAINAGE AMOUNT: $${retainageHeld.toLocaleString()}` : ''}
${additionalNotes ? `ADDITIONAL NOTES: ${additionalNotes}` : ''}

Write a formal, professional ${config.title}. 3-4 paragraphs. Include:
- Proper salutation and reference to the contract
- Clear statement of what is being issued
- Any conditions, requirements, or next steps
- Professional closing

Return only the letter body text (no JSON, no markdown, no subject line). Start with "Dear ${ownerName}," or appropriate salutation.`,
      }],
    })
    letterBody = msg.content[0]?.type === 'text' ? msg.content[0].text : ''
  } catch {
    letterBody = `Dear ${ownerName},\n\nThis letter serves as the ${config.title} for ${project?.name || 'the project'} under Contract No. ${contractNo}, effective ${effectiveDateStr}.\n\nRespectfully,\n${gcName}`
  }

  const htmlContent = `<!DOCTYPE html>
<html>
<head>
  <meta charset="utf-8"><title>${config.title} — ${project?.name || 'Project'}</title>
  <style>
    @page { size: letter portrait; margin: 1in 0.75in; }
    @media print { .no-print { display:none!important; } }
    * { box-sizing:border-box; margin:0; padding:0; }
    body { font-family: Arial, sans-serif; font-size: 10.5pt; color: #1a1a1a; background: #fff; line-height: 1.7; }
    .header { background: linear-gradient(135deg,#1a1a2e,#16213e); color: #fff; padding: 16px 22px; display: flex; justify-content: space-between; }
    .company-name { font-size: 14pt; font-weight: 900; color: #D4A017; }
    .gold-bar { height: 4px; background: linear-gradient(90deg,#D4A017,#F0C040); }
    .content { padding: 28px 32px; }
    .letter-title { font-size: 14pt; font-weight: 900; text-transform: uppercase; letter-spacing: .04em; color: #1a1a2e; border-bottom: 2px solid #D4A017; padding-bottom: 8px; margin-bottom: 20px; }
    .meta-grid { display: grid; grid-template-columns: 120px 1fr; gap: 4px 12px; font-size: 9.5pt; margin-bottom: 20px; }
    .meta-label { font-weight: 700; color: #666; }
    .letter-body { font-size: 10.5pt; white-space: pre-wrap; line-height: 1.8; }
    .sig-block { margin-top: 40px; }
    .sig-line { border-bottom: 1px solid #333; margin: 14px 0 4px; min-height: 32px; }
    .print-btn { position: fixed; top: 10px; right: 10px; background: #D4A017; color: #000; border: none; padding: 7px 16px; font-weight: 700; cursor: pointer; border-radius: 6px; }
  </style>
</head>
<body>
  <button class="print-btn no-print" onclick="window.print()">🖨️ Print / Save PDF</button>
  <div class="header">
    <div>
      <div class="company-name">${gcName}</div>
      <div style="font-size:8pt;color:rgba(255,255,255,.65);margin-top:4px">${gcAddr}</div>
    </div>
    <div style="text-align:right;font-size:8.5pt;color:rgba(255,255,255,.75);line-height:1.7">
      ${gc?.company_phone || ''}<br>${gc?.company_email || ''}
      ${gc?.license_number ? '<br>License: ' + gc.license_number : ''}
    </div>
  </div>
  <div class="gold-bar"></div>
  <div class="content">
    <div style="text-align:right;font-size:10pt;margin-bottom:24px">${today}</div>
    <div class="letter-title">${config.title}</div>
    <div class="meta-grid">
      <span class="meta-label">Project:</span><span>${project?.name || '—'}</span>
      <span class="meta-label">Address:</span><span>${[project?.address, project?.city ? `${project.city}, ${project.state}` : ''].filter(Boolean).join(', ')}</span>
      <span class="meta-label">Contract No.:</span><span>${contractNo}</span>
      <span class="meta-label">Contract Value:</span><span>$${contractValue.toLocaleString()}</span>
      <span class="meta-label">Effective Date:</span><span><strong>${effectiveDateStr}</strong></span>
      ${typed === 'retainage_release' ? `<span class="meta-label">Retainage:</span><span style="color:#D4A017;font-weight:700">$${retainageHeld.toLocaleString()}</span>` : ''}
    </div>
    <div class="letter-body">${letterBody}</div>
    <div class="sig-block">
      <div style="font-size:9.5pt;font-weight:700;margin-bottom:10px">Respectfully submitted,</div>
      <div class="sig-line">&nbsp;</div><div style="font-size:8.5pt;color:#666">Authorized Signature</div>
      <div style="margin-top:8px"><strong>${gc?.signature_name || '—'}</strong>, ${gc?.signature_title || '—'}<br>${gcName}</div>
    </div>
    <div style="margin-top:20px;font-size:7.5pt;color:#aaa">${DISCLAIMER}</div>
  </div>
</body>
</html>`

  const letterTitle = `${config.title} — ${project?.name || 'Project'}`
  const { data: letter, error: lErr } = await supabase
    .from('milestone_letters')
    .insert({
      tenant_id: tenantId,
      project_id: projectId,
      letter_type: typed,
      title: letterTitle,
      html_content: htmlContent,
      status: 'draft',
      issued_date: new Date().toISOString().split('T')[0],
      effective_date: effectiveDate || new Date().toISOString().split('T')[0],
      sent_to: ownerName,
      ai_generated: true,
    })
    .select('id')
    .single()

  if (lErr) return NextResponse.json({ error: lErr.message }, { status: 500 })

  await supabase.from('generated_documents').insert({
    tenant_id: tenantId,
    project_id: projectId,
    doc_type: `milestone_letter_${typed}`,
    status: 'generated',
    source_type: 'milestone_letter',
    source_id: letter?.id,
    data_snapshot: { letter_type: typed, title: letterTitle, effective_date: effectiveDate },
  })

  return NextResponse.json({
    success: true,
    letterId: letter?.id,
    title: letterTitle,
    letterType: typed,
    effectiveDate: effectiveDate || new Date().toISOString().split('T')[0],
    sentTo: ownerName,
    html_content: htmlContent,
  })
}

export async function GET(req: NextRequest) {
  const auth = await requireAuth()
  if (auth instanceof NextResponse) return auth
  const { supabase, tenantId } = auth
  const letterId = req.nextUrl.searchParams.get('id')
  if (!letterId) return NextResponse.json({ error: 'id required' }, { status: 400 })
  const { data: letter } = await supabase
    .from('milestone_letters')
    .select('html_content')
    .eq('id', letterId)
    .eq('tenant_id', tenantId)
    .single()
  if (!letter?.html_content) return NextResponse.json({ error: 'Not generated' }, { status: 404 })
  return new Response(letter.html_content, { headers: { 'Content-Type': 'text/html; charset=utf-8' } })
}
