import { NextRequest, NextResponse } from 'next/server'
import { requireAuth } from '@/lib/auth-helper'
import Anthropic from '@anthropic-ai/sdk'
import { getLienLaw } from '@/lib/lien-law/states'

export const runtime = 'nodejs'
export const maxDuration = 120

const DISCLAIMER = 'DISCLAIMER: This document was generated by Saguaro Construction Intelligence Platform. This document does not constitute legal advice. Verify compliance with current state statutes and consult a licensed state construction attorney before relying on this document for legal purposes.'

export async function POST(req: NextRequest) {
  const auth = await requireAuth()
  if (auth instanceof NextResponse) return auth
  const { supabase, tenantId } = auth

  const body = await req.json()
  const { bidSubmissionId, bidPackageId, projectId, manualSub } = body as {
    bidSubmissionId?: string
    bidPackageId?: string
    projectId?: string
    manualSub?: {
      name?: string
      email?: string
      company?: string
      trade?: string
      scope?: string
      amount?: number
    }
  }
  if (!projectId) return NextResponse.json({ error: 'projectId required' }, { status: 400 })

  const [{ data: project }, { data: gc }, pkgRes, submissionRes] = await Promise.all([
    supabase.from('projects').select('*').eq('tenant_id', tenantId).eq('id', projectId).single(),
    supabase.from('tenant_settings').select('*').eq('tenant_id', tenantId).maybeSingle(),
    bidPackageId ? supabase.from('bid_packages').select('*').eq('tenant_id', tenantId).eq('id', bidPackageId).single() : Promise.resolve({ data: null }),
    bidSubmissionId ? supabase.from('bid_submissions').select('*').eq('tenant_id', tenantId).eq('id', bidSubmissionId).single() : Promise.resolve({ data: null }),
  ])

  // eslint-disable-next-line @typescript-eslint/no-explicit-any
  const pkg = (pkgRes as any).data
  // eslint-disable-next-line @typescript-eslint/no-explicit-any
  const submission = (submissionRes as any).data

  const stateCode = project?.state || 'XX'
  const law = getLienLaw(stateCode)
  const today = new Date().toLocaleDateString('en-US', { year: 'numeric', month: 'long', day: 'numeric' })
  const gcName = gc?.company_name || 'General Contractor'
  const gcAddr = gc?.company_address
    ? `${gc.company_address}, ${gc.company_city || ''}, ${gc.company_state || ''} ${gc.company_zip || ''}`.trim()
    : ''
  const subName = manualSub?.name || submission?.company_name || submission?.sub_name || 'Subcontractor'
  const subEmail = manualSub?.email || submission?.contact_email || submission?.sub_email || ''
  const contractAmount = Number(manualSub?.amount || submission?.base_bid || submission?.amount || 0)
  const retainagePct = Number(gc?.default_retainage_pct || 10)
  const paymentTerms = gc?.default_payment_terms ? `Net ${gc.default_payment_terms}` : 'Net 30'
  const trade = manualSub?.trade || pkg?.csi_division || pkg?.trade || 'General Construction'
  const scopeFromPackage = manualSub?.scope || pkg?.scope_summary || pkg?.description || ''

  const client = new Anthropic()
  const msg = await client.messages.create({
    model: 'claude-sonnet-4-20250514',
    max_tokens: 4000,
    system: `You are a construction contract attorney specializing in AIA subcontract agreements.
Generate a professional, comprehensive subcontract agreement.
Return ONLY the contract body text (no JSON wrapper, plain text with section headers).`,
    messages: [{
      role: 'user',
      content: `Generate a complete subcontract agreement for the following:

GENERAL CONTRACTOR: ${gcName}
  Address: ${gcAddr}
  License: ${gc?.license_number || 'N/A'} (${stateCode})
  Contact: ${gc?.signature_name || 'Project Manager'}${gc?.signature_title ? ', ' + gc.signature_title : ''}

SUBCONTRACTOR: ${subName}
  Trade: ${trade}
  Contract Amount: $${contractAmount.toLocaleString()}
  Retainage: ${retainagePct}%
  Payment Terms: ${paymentTerms}

PROJECT: ${project?.name || 'Project'}
  Address: ${[project?.address, project?.city ? `${project.city}, ${project.state}` : ''].filter(Boolean).join(', ')}
  Owner: ${project?.owner_name || 'Owner'}
  Start Date: ${project?.start_date || 'Per NTP'}
  Completion Date: ${project?.end_date || 'Per Schedule'}

SCOPE OF WORK:
${scopeFromPackage || `[Trade: ${trade}]`}

STATE LAW (${law.stateName}):
  Mechanic's Lien Statute: ${law.lienStatute}
  Preliminary Notice: ${law.preliminaryNoticeRequired ? `Required within ${law.preliminaryNoticeDays} days` : 'Not required'}
  Notarization: ${law.notarizationRequired ? 'Required' : 'Not required'}

Generate a complete subcontract with these articles:
ARTICLE 1 - THE SUBCONTRACT DOCUMENTS
ARTICLE 2 - RELATIONSHIP OF THE PARTIES
ARTICLE 3 - SUBCONTRACTOR'S RESPONSIBILITIES
ARTICLE 4 - CONTRACTOR'S RESPONSIBILITIES
ARTICLE 5 - SUBCONTRACT AMOUNT AND PAYMENTS (include retainage, payment timing, lien waiver requirements)
ARTICLE 6 - CHANGES IN THE WORK
ARTICLE 7 - INSURANCE AND BONDS
ARTICLE 8 - SCHEDULE AND TIME OF COMPLETION
ARTICLE 9 - INDEMNIFICATION
ARTICLE 10 - DISPUTE RESOLUTION
ARTICLE 11 - TERMINATION
ARTICLE 12 - GENERAL PROVISIONS (governing law = ${law.stateName}, lien rights, notice requirements)

Use professional AIA A401-style language. Be specific and enforceable.
Include blanks for dates and notary where appropriate.`,
    }],
  })

  const contractBody = msg.content[0]?.type === 'text' ? msg.content[0].text : ''

  const { count } = await supabase
    .from('contracts')
    .select('*', { count: 'exact', head: true })
    .eq('project_id', projectId)
    .eq('tenant_id', tenantId)
  const contractNumber = `SC-${project?.project_number || projectId.slice(0, 4).toUpperCase()}-${String((count || 0) + 1).padStart(3, '0')}`
  const contractTitle = `${subName} — ${trade} Subcontract`

  const htmlContent = `<!DOCTYPE html>
<html>
<head>
  <meta charset="utf-8">
  <title>Subcontract — ${subName}</title>
  <style>
    @page { size: letter portrait; margin: 1in 0.75in; }
    @media print { .no-print { display:none!important; } }
    * { box-sizing:border-box; margin:0; padding:0; }
    body { font-family: 'Times New Roman', Times, serif; font-size: 10.5pt; color: #000; background: #fff; line-height: 1.6; }
    .header { background: linear-gradient(135deg,#1a1a2e,#16213e); color: #fff; padding: 16px 22px; display: flex; justify-content: space-between; align-items: center; }
    .company-name { font-size: 14pt; font-weight: 900; color: #D4A017; font-family: Arial,sans-serif; }
    .gold-bar { height: 4px; background: linear-gradient(90deg,#D4A017,#F0C040); }
    .doc-title-bar { background: #f7f8f8; border-bottom: 2px solid #D4A017; padding: 10px 22px; text-align: center; }
    .doc-title { font-size: 13pt; font-weight: 700; text-transform: uppercase; letter-spacing: 0.04em; font-family: Arial; }
    .content { padding: 20px 22px; }
    .summary-box { border: 2px solid #D4A017; border-radius: 8px; padding: 14px; margin-bottom: 20px; background: #fffcf0; }
    .summary-grid { display: grid; grid-template-columns: 1fr 1fr; gap: 8px; font-size: 9.5pt; font-family: Arial; }
    .summary-grid dt { font-weight: 700; color: #555; }
    .summary-grid dd { color: #000; }
    .contract-body { white-space: pre-wrap; font-size: 10.5pt; line-height: 1.7; }
    .sig-section { margin-top: 32px; page-break-inside: avoid; }
    .sig-grid { display: grid; grid-template-columns: 1fr 1fr; gap: 32px; font-family: Arial; }
    .sig-box { border: 1px solid #999; padding: 14px; }
    .sig-line { border-bottom: 1px solid #333; margin: 14px 0 4px; min-height: 32px; }
    .sig-label { font-size: 8.5pt; color: #666; }
    .print-btn { position: fixed; top: 10px; right: 10px; background: #D4A017; color: #000; border: none; padding: 7px 16px; font-weight: 700; cursor: pointer; border-radius: 6px; font-family: Arial; }
  </style>
</head>
<body>
  <button class="print-btn no-print" onclick="window.print()">🖨️ Print / Save PDF</button>
  <div class="header">
    <div><div class="company-name">${gcName}</div><div style="font-size:8pt;color:rgba(255,255,255,.65);margin-top:3px">${gcAddr}</div></div>
    <div style="text-align:right;font-size:9pt;color:rgba(255,255,255,.75)">SUBCONTRACT AGREEMENT<br>${today}</div>
  </div>
  <div class="gold-bar"></div>
  <div class="doc-title-bar">
    <div class="doc-title">Subcontract Agreement</div>
    <div style="font-size:9pt;color:#666;font-family:Arial;margin-top:3px">Contract No. ${contractNumber} · ${today}</div>
  </div>
  <div class="content">
    <div class="summary-box">
      <div style="font-size:10pt;font-weight:900;font-family:Arial;margin-bottom:10px;color:#1a1a2e">CONTRACT SUMMARY</div>
      <dl class="summary-grid">
        <dt>Subcontractor:</dt><dd>${subName}</dd>
        <dt>Trade / Scope:</dt><dd>${trade}</dd>
        <dt>Project:</dt><dd>${project?.name || 'Project'}</dd>
        <dt>Contract Amount:</dt><dd style="color:#D4A017;font-weight:700">$${contractAmount.toLocaleString()}</dd>
        <dt>Retainage:</dt><dd>${retainagePct}%</dd>
        <dt>Payment Terms:</dt><dd>${paymentTerms}</dd>
        <dt>Start Date:</dt><dd>${project?.start_date || 'Per NTP'}</dd>
        <dt>Completion:</dt><dd>${project?.end_date || 'Per Schedule'}</dd>
        <dt>Governing Law:</dt><dd>${law.stateName} (${law.lienStatute})</dd>
        <dt>Insurance Required:</dt><dd>Yes — GL $1M/$2M + WC + Auto</dd>
      </dl>
    </div>
    <div class="contract-body">${contractBody.replace(/</g, '&lt;').replace(/>/g, '&gt;')}</div>
    <div class="sig-section">
      <div style="font-family:Arial;font-size:10pt;font-weight:900;margin-bottom:14px;text-transform:uppercase;border-bottom:2px solid #D4A017;padding-bottom:4px">EXECUTION</div>
      <div class="sig-grid">
        <div class="sig-box">
          <strong style="font-family:Arial">GENERAL CONTRACTOR</strong><br>
          <span style="font-size:9.5pt">${gcName}</span>
          <div class="sig-line">&nbsp;</div><div class="sig-label">Authorized Signature</div>
          <div class="sig-line">${gc?.signature_name || '&nbsp;'}</div><div class="sig-label">Printed Name</div>
          <div class="sig-line">${gc?.signature_title || '&nbsp;'}</div><div class="sig-label">Title</div>
          <div class="sig-line">&nbsp;</div><div class="sig-label">Date</div>
        </div>
        <div class="sig-box">
          <strong style="font-family:Arial">SUBCONTRACTOR</strong><br>
          <span style="font-size:9.5pt">${subName}</span>
          <div class="sig-line">&nbsp;</div><div class="sig-label">Authorized Signature</div>
          <div class="sig-line">&nbsp;</div><div class="sig-label">Printed Name</div>
          <div class="sig-line">&nbsp;</div><div class="sig-label">Title</div>
          <div class="sig-line">&nbsp;</div><div class="sig-label">Date</div>
        </div>
      </div>
    </div>
    <div style="margin-top:20px;font-size:7.5pt;color:#aaa;font-family:Arial">${DISCLAIMER} Governing law: State of ${law.stateName} (${law.lienStatute}).</div>
  </div>
</body>
</html>`

  const { data: contract, error: cErr } = await supabase.from('contracts').insert({
    tenant_id: tenantId,
    project_id: projectId,
    title: contractTitle,
    contract_number: contractNumber,
    contract_type: 'subcontract',
    party_name: subName,
    party_email: subEmail,
    party_company: manualSub?.company || submission?.company_name || subName,
    trade,
    scope_of_work: scopeFromPackage,
    scope_summary: `${trade} subcontract — $${contractAmount.toLocaleString()}`,
    amount: contractAmount,
    contract_amount: contractAmount,
    retainage_pct: retainagePct,
    status: 'draft',
    start_date: project?.start_date || null,
    end_date: project?.end_date || null,
    bid_package_id: bidPackageId || null,
    insurance_required: true,
    bond_required: contractAmount > 500000,
    ai_generated: true,
    ai_generated_at: new Date().toISOString(),
    html_content: htmlContent,
  }).select('id, signing_token').single()

  if (cErr) return NextResponse.json({ error: cErr.message }, { status: 500 })

  await supabase.from('contract_documents').insert({
    tenant_id: tenantId,
    contract_id: contract?.id,
    title: contractTitle,
    doc_type: 'subcontract',
  })

  await supabase.from('generated_documents').insert({
    tenant_id: tenantId,
    project_id: projectId,
    doc_type: 'subcontract',
    status: 'generated',
    source_type: 'contract',
    source_id: contract?.id,
    data_snapshot: { contract_number: contractNumber, party: subName, amount: contractAmount, trade },
  })

  // Auto-generate 6-payment schedule stored as JSON in contracts.payment_schedule
  if (contract?.id && contractAmount > 0) {
    const paySchedule = [
      { payment_number: 1, description: 'Mobilization', percent: 10, amount: Math.round(contractAmount * 0.10) },
      { payment_number: 2, description: 'Monthly progress — 30% complete', percent: 20, amount: Math.round(contractAmount * 0.20) },
      { payment_number: 3, description: 'Monthly progress — 60% complete', percent: 20, amount: Math.round(contractAmount * 0.20) },
      { payment_number: 4, description: 'Monthly progress — 90% complete', percent: 20, amount: Math.round(contractAmount * 0.20) },
      { payment_number: 5, description: 'Substantial completion', percent: 20, amount: Math.round(contractAmount * 0.20) },
      { payment_number: 6, description: 'Final payment (retainage release)', percent: 10, amount: Math.round(contractAmount * 0.10) },
    ]
    await supabase.from('contracts').update({ payment_schedule: paySchedule })
      .eq('id', contract.id).eq('tenant_id', tenantId)
  }

  return NextResponse.json({
    success: true,
    contractId: contract?.id,
    signingToken: contract?.signing_token,
    contractNumber,
    htmlAvailable: true,
    html_content: htmlContent,
    partyName: subName,
    trade,
    contractAmount,
    retainagePct,
    projectId,
  })
}
