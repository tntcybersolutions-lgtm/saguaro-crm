import { NextRequest, NextResponse } from 'next/server'
import { requireAuth } from '@/lib/auth-helper'

export const runtime = 'nodejs'
export const maxDuration = 60

const DISCLAIMER = 'DISCLAIMER: This WH-347 was generated by Saguaro Construction Intelligence Platform. This document does not constitute legal advice. Verify compliance with current state statutes and consult a licensed state construction attorney before relying on this document for legal purposes. Actual deductions may vary — verify with your payroll system before submitting.'

export async function POST(req: NextRequest) {
  const auth = await requireAuth()
  if (auth instanceof NextResponse) return auth
  const { supabase, tenantId } = auth

  const body = await req.json()
  const projectId = body.projectId as string | undefined
  const weekEnding = body.weekEnding as string | undefined
  if (!projectId || !weekEnding) {
    return NextResponse.json({ error: 'projectId and weekEnding required' }, { status: 400 })
  }

  const weekEnd = new Date(weekEnding)
  const weekStart = new Date(weekEnd)
  weekStart.setDate(weekStart.getDate() - 6)
  const weekStartStr = weekStart.toISOString().split('T')[0]

  const [{ data: project }, { data: gc }, { data: timeEntries }] = await Promise.all([
    supabase
      .from('projects')
      .select('name, address, city, state, project_number, davis_bacon_wage_decision, prevailing_wage, federal_project_number, awarding_agency').eq('tenant_id', tenantId)
      .eq('id', projectId)
      .single(),
    supabase
      .from('tenant_settings')
      .select('company_name, company_address, company_city, company_state, company_zip, signature_name, signature_title')
      .eq('tenant_id', tenantId)
      .maybeSingle(),
    supabase
      .from('time_entries')
      .select('*, employees!inner(first_name, last_name, full_name, trade, title, regular_rate, overtime_rate, doubletime_rate, employment_type)')
      .eq('project_id', projectId)
      .eq('tenant_id', tenantId)
      .gte('work_date', weekStartStr)
      .lte('work_date', weekEnding),
  ])

  const today = new Date().toLocaleDateString('en-US', { year: 'numeric', month: 'long', day: 'numeric' })
  const gcName = gc?.company_name || 'General Contractor'
  const gcAddr = gc?.company_address
    ? `${gc.company_address}, ${gc.company_city || ''}, ${gc.company_state || ''} ${gc.company_zip || ''}`.trim()
    : ''

  interface Worker {
    name: string
    trade: string
    title: string
    regularRate: number
    overtimeRate: number
    doubletimeRate: number
    dayHours: Record<string, { regular: number; overtime: number; doubletime: number }>
    totalRegular: number
    totalOvertime: number
    totalDoubletime: number
    totalHours: number
    grossWages: number
    deductions: number
    netWages: number
  }

  const employeeMap = new Map<string, Worker>()

  for (const rawEntry of (timeEntries || [])) {
    const entry = rawEntry as Record<string, unknown>
    const emp = (entry.employees as Record<string, unknown>) || {}
    const empId = String(entry.employee_id || '')
    if (!empId) continue

    const empName = String(
      emp.full_name || `${emp.first_name || ''} ${emp.last_name || ''}`.trim() || 'Worker'
    )
    const regRate = Number(entry.regular_rate_used || emp.regular_rate || 0)
    const otRate = Number(entry.overtime_rate_used || emp.overtime_rate || regRate * 1.5)
    const dtRate = Number(entry.doubletime_rate_used || emp.doubletime_rate || regRate * 2)

    if (!employeeMap.has(empId)) {
      employeeMap.set(empId, {
        name: empName,
        trade: String(emp.trade || entry.csi_division || 'Laborer'),
        title: String(emp.title || ''),
        regularRate: regRate,
        overtimeRate: otRate,
        doubletimeRate: dtRate,
        dayHours: {},
        totalRegular: 0,
        totalOvertime: 0,
        totalDoubletime: 0,
        totalHours: 0,
        grossWages: 0,
        deductions: 0,
        netWages: 0,
      })
    }
    const worker = employeeMap.get(empId)!
    const dayKey = String(entry.work_date || '')
    if (!worker.dayHours[dayKey]) worker.dayHours[dayKey] = { regular: 0, overtime: 0, doubletime: 0 }
    worker.dayHours[dayKey].regular += Number(entry.regular_hours || 0)
    worker.dayHours[dayKey].overtime += Number(entry.overtime_hours || 0)
    worker.dayHours[dayKey].doubletime += Number(entry.doubletime_hours || 0)
    worker.totalRegular += Number(entry.regular_hours || 0)
    worker.totalOvertime += Number(entry.overtime_hours || 0)
    worker.totalDoubletime += Number(entry.doubletime_hours || 0)
  }

  let totalGross = 0
  const workers: Worker[] = Array.from(employeeMap.values()).map((w) => {
    w.totalHours = w.totalRegular + w.totalOvertime + w.totalDoubletime
    w.grossWages =
      w.totalRegular * w.regularRate +
      w.totalOvertime * w.overtimeRate +
      w.totalDoubletime * w.doubletimeRate
    w.deductions = Math.round(w.grossWages * 0.2265)
    w.netWages = Math.round(w.grossWages - w.deductions)
    totalGross += w.grossWages
    return w
  })

  const totalDeductions = workers.reduce((s, w) => s + w.deductions, 0)
  const totalNet = workers.reduce((s, w) => s + w.netWages, 0)

  const { count: existingCount } = await supabase
    .from('certified_payroll')
    .select('*', { count: 'exact', head: true })
    .eq('project_id', projectId)
    .eq('tenant_id', tenantId)
  const payrollNumber = (existingCount || 0) + 1

  const fmt = (n: number) =>
    `$${Number(n).toLocaleString('en-US', { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`

  const days: string[] = []
  for (let i = 0; i < 7; i++) {
    const d = new Date(weekStart)
    d.setDate(d.getDate() + i)
    days.push(d.toISOString().split('T')[0])
  }
  const dayLabels = ['Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat', 'Sun']

  const workerRows = workers
    .map((w) => {
      const dayCells = days
        .map((d) => {
          const hrs = w.dayHours[d]
          if (!hrs || hrs.regular + hrs.overtime + hrs.doubletime === 0) {
            return '<td style="text-align:center;font-size:8pt">—</td>'
          }
          const total = hrs.regular + hrs.overtime + hrs.doubletime
          return `<td style="text-align:center;font-size:8pt">${total.toFixed(1)}</td>`
        })
        .join('')
      return `
      <tr>
        <td style="font-size:8.5pt;font-weight:700">${w.name}</td>
        <td style="font-size:8pt">${w.trade}</td>
        <td style="font-size:8pt;text-align:right">${fmt(w.regularRate)}</td>
        ${dayCells}
        <td style="font-size:8pt;text-align:right;font-weight:700">${w.totalHours.toFixed(1)}</td>
        <td style="font-size:8pt;text-align:right;color:#D4A017;font-weight:700">${fmt(w.grossWages)}</td>
        <td style="font-size:8pt;text-align:right">${fmt(w.deductions)}</td>
        <td style="font-size:8pt;text-align:right;font-weight:700">${fmt(w.netWages)}</td>
      </tr>`
    })
    .join('\n')

  const projectLocation = [project?.address, project?.city ? `${project.city}, ${project.state}` : '']
    .filter(Boolean)
    .join(', ')

  const htmlContent = `<!DOCTYPE html>
<html>
<head>
  <meta charset="utf-8">
  <title>WH-347 Certified Payroll — Week Ending ${weekEnding}</title>
  <style>
    @page { size: letter landscape; margin: 0.4in; }
    @media print { .no-print { display:none!important; } }
    * { box-sizing:border-box; margin:0; padding:0; }
    body { font-family: Arial, Helvetica, sans-serif; font-size: 9pt; color: #000; background: #fff; }
    .header { background: #1a1a2e; color: #fff; padding: 10px 14px; display: flex; justify-content: space-between; align-items: center; }
    .company-name { font-size: 13pt; font-weight: 900; color: #D4A017; }
    .doc-title { font-size: 11pt; font-weight: 900; text-align: center; padding: 8px; border-bottom: 2px solid #D4A017; background: #f7f8fa; }
    .info-grid { display: grid; grid-template-columns: 1fr 1fr 1fr; gap: 8px; padding: 10px 0; font-size: 8.5pt; }
    .info-label { font-weight: 700; color: #555; }
    table.payroll { width: 100%; border-collapse: collapse; margin-top: 10px; font-size: 8pt; }
    table.payroll th { background: #1a1a2e; color: #fff; padding: 4px 5px; text-align: center; border: 1px solid #666; white-space: nowrap; }
    table.payroll td { padding: 3px 5px; border: 1px solid #ddd; vertical-align: middle; }
    table.payroll tr:nth-child(even) { background: #f9f9f9; }
    .totals-row td { background: #1a1a2e; color: #D4A017; font-weight: 900; text-align: right; }
    .compliance-section { margin-top: 16px; padding: 12px; border: 2px solid #333; font-size: 8.5pt; line-height: 1.6; }
    .sig-grid { display: grid; grid-template-columns: 1fr 1fr; gap: 20px; margin-top: 12px; }
    .sig-line { border-bottom: 1px solid #333; margin: 10px 0 3px; min-height: 24px; }
    .print-btn { position: fixed; top: 10px; right: 10px; background: #D4A017; color: #000; border: none; padding: 7px 16px; font-weight: 700; cursor: pointer; border-radius: 6px; }
  </style>
</head>
<body>
  <button class="print-btn no-print" onclick="window.print()">🖨️ Print / Save PDF</button>
  <div class="header">
    <div class="company-name">${gcName}</div>
    <div style="font-size:9pt;color:rgba(255,255,255,.8)">
      U.S. Department of Labor — Payroll (For Contractor's Optional Use) WH-347
    </div>
    <div style="font-size:8pt;color:rgba(255,255,255,.7)">Payroll No. ${payrollNumber}</div>
  </div>
  <div class="doc-title">CERTIFIED PAYROLL — WEEK ENDING ${weekEnding} — PAYROLL NO. ${payrollNumber}</div>

  <div style="padding:8px 0">
    <div class="info-grid">
      <div><span class="info-label">Contractor:</span> ${gcName}</div>
      <div><span class="info-label">Address:</span> ${gcAddr}</div>
      <div><span class="info-label">Payroll No.:</span> ${payrollNumber}</div>
      <div><span class="info-label">Project:</span> ${project?.name || '—'}</div>
      <div><span class="info-label">Project No.:</span> ${project?.project_number || project?.federal_project_number || '—'}</div>
      <div><span class="info-label">Week Ending:</span> ${weekEnding}</div>
      <div><span class="info-label">Location:</span> ${projectLocation || '—'}</div>
      <div><span class="info-label">Wage Decision:</span> ${project?.davis_bacon_wage_decision || '—'}</div>
      <div><span class="info-label">Awarding Agency:</span> ${project?.awarding_agency || '—'}</div>
    </div>
  </div>

  <table class="payroll">
    <thead>
      <tr>
        <th style="width:120px">Name &amp; Individual Identifying Number</th>
        <th style="width:80px">Work Classification</th>
        <th style="width:60px">Hourly Rate</th>
        ${dayLabels.map((d) => `<th style="width:40px">${d}</th>`).join('')}
        <th style="width:50px">Total Hours</th>
        <th style="width:70px">Gross Wages</th>
        <th style="width:60px">Deductions</th>
        <th style="width:70px">Net Wages</th>
      </tr>
    </thead>
    <tbody>
      ${workerRows || '<tr><td colspan="12" style="text-align:center;padding:20px;color:#888">No time entries found for this week. Add time entries in the Time Tracking section.</td></tr>'}
    </tbody>
    <tfoot>
      <tr class="totals-row">
        <td colspan="9" style="text-align:right;font-size:9pt">TOTALS:</td>
        <td>${workers.reduce((s, w) => s + w.totalHours, 0).toFixed(1)}</td>
        <td>${fmt(totalGross)}</td>
        <td>${fmt(totalDeductions)}</td>
        <td>${fmt(totalNet)}</td>
      </tr>
    </tfoot>
  </table>

  <div class="compliance-section">
    <strong>STATEMENT OF COMPLIANCE</strong><br><br>
    I, <strong>${gc?.signature_name || '____________________'}</strong>, ${gc?.signature_title || '____________________'} of <strong>${gcName}</strong>,
    do hereby state: (1) That the payroll records for the payroll period commencing on <strong>${weekStartStr}</strong> and ending <strong>${weekEnding}</strong> show the name, address,
    and social security number of each laborer and mechanic employed on the project during the payroll period; (2) That during the payroll period every laborer and mechanic employed on the subject project has been paid the full weekly wages earned; (3) That each laborer or mechanic employed on the subject project paid not less than the applicable wage rates and fringe benefits or cash equivalents for the classification of work performed, as specified in the applicable wage determination incorporated into the contract.
    <br><br>
    <div style="font-size:8pt;color:#F85149">⚠️ NOTE: Deductions shown are estimated (FICA 7.65% + Federal 15%). Verify actual deductions before submitting to awarding agency.</div>
    <div class="sig-grid">
      <div>
        <div class="sig-line">&nbsp;</div>
        <div style="font-size:7.5pt;color:#666">Signature / Date</div>
        <div style="margin-top:8px">${gc?.signature_name || '____________________'}, ${gc?.signature_title || '____________________'}</div>
      </div>
      <div>
        <div style="font-size:8pt;font-weight:700;margin-bottom:6px">CERTIFICATE</div>
        <div style="font-size:8pt">I hereby certify that all information in this payroll is true, accurate, and complete and that all workers have been paid wages required by Federal Wage and Hour Laws.</div>
      </div>
    </div>
  </div>
  <div style="margin-top:8px;font-size:7pt;color:#aaa">
    ${DISCLAIMER}
  </div>
</body>
</html>`

  const { data: cp, error: cpErr } = await supabase
    .from('certified_payroll')
    .insert({
      tenant_id: tenantId,
      project_id: projectId,
      week_ending: weekEnding,
      payroll_number: payrollNumber,
      contractor_name: gcName,
      contractor_address: gcAddr,
      project_name: project?.name || '',
      project_number: project?.project_number || '',
      project_location: projectLocation,
      awarding_agency: project?.awarding_agency || '',
      wage_decision: project?.davis_bacon_wage_decision || '',
      entries: workers.map((w) => ({
        name: w.name,
        trade: w.trade,
        regularRate: w.regularRate,
        overtimeRate: w.overtimeRate,
        totalRegular: w.totalRegular,
        totalOvertime: w.totalOvertime,
        totalHours: w.totalHours,
        grossWages: w.grossWages,
        deductions: w.deductions,
        netWages: w.netWages,
      })),
      total_gross: Math.round(totalGross),
      total_deductions: Math.round(totalDeductions),
      total_net: Math.round(totalNet),
      html_content: htmlContent,
      ai_generated: workers.length === 0,
      status: 'draft',
    })
    .select('id')
    .single()

  if (cpErr) return NextResponse.json({ error: cpErr.message }, { status: 500 })

  await supabase.from('generated_documents').insert({
    tenant_id: tenantId,
    project_id: projectId,
    doc_type: 'certified_payroll_wh347',
    status: 'generated',
    source_type: 'certified_payroll',
    source_id: cp?.id,
    data_snapshot: {
      payroll_number: payrollNumber,
      week_ending: weekEnding,
      worker_count: workers.length,
      total_gross: totalGross,
    },
  })

  return NextResponse.json({
    success: true,
    payrollId: cp?.id,
    payrollNumber,
    workerCount: workers.length,
    totalGross,
    weekEnding,
    html_content: htmlContent,
  })
}

export async function GET(req: NextRequest) {
  const auth = await requireAuth()
  if (auth instanceof NextResponse) return auth
  const { supabase, tenantId } = auth
  const payrollId = req.nextUrl.searchParams.get('id')
  if (!payrollId) return NextResponse.json({ error: 'id required' }, { status: 400 })
  const { data: cp } = await supabase
    .from('certified_payroll')
    .select('html_content')
    .eq('id', payrollId)
    .eq('tenant_id', tenantId)
    .single()
  if (!cp?.html_content) return NextResponse.json({ error: 'Not generated' }, { status: 404 })
  return new Response(cp.html_content, { headers: { 'Content-Type': 'text/html; charset=utf-8' } })
}
