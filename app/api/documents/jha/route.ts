import { NextRequest, NextResponse } from 'next/server';
import { createServerClient } from '@/lib/supabase-server';
import { requirePermission } from '@/lib/permissions';
import { generateJHA } from '@/lib/document-templates/jha-generator';
import { apiError } from '@/lib/api-error';

export async function POST(req: NextRequest) {
  const g = await requirePermission(req, 'Documents', 'Edit');
  if (!g.ok) return g.res;
  try {
    const body = await req.json();
    const db = createServerClient();

    const { data: project, error: pErr } = await db
      .from('projects')
      .select('*')
      .eq('id', body.projectId)
      .eq('tenant_id', g.user.tenantId)
      .maybeSingle();
    /* THE TENANT CHECK WAS HERE AND ITS ANSWER WAS THROWN AWAY.
       The query is correctly scoped — .eq('tenant_id', g.user.tenantId) — but
       `const { data: project }` drops the error, nothing tested `project`, and
       the generator below was then called with the raw body.projectId anyway.
       .single() on no rows returns { data: null, error } rather than throwing,
       so a project belonging to another company sailed straight through.
       Verified against production: signed in as one tenant, posting another
       tenant's projectId returned 200 with a real PDF built from THEIR project,
       and saveDocument filed the row under THEIR tenant — because it derives
       the tenant from the project row, not from the caller. Five documents
       about a customer's job appeared in that customer's Document Library,
       generated by a different company's login.
       The check now has to pass before anything is generated. */
    if (pErr) throw pErr;
    if (!project) return NextResponse.json({ error: 'Project not found' }, { status: 404 });


    // Determine trade from request or project building type
    const trade = body.trade || (project as { building_type?: string })?.building_type || 'general';

    const result = await generateJHA({
      projectId: body.projectId,
      trade,
      hazards: body.hazards,
    });

    return NextResponse.json({ pdfUrl: result.pdfUrl, success: true });
  } catch (err: unknown) {
    return apiError('documents/jha POST', err, 'Document generation failed');
  }
}
