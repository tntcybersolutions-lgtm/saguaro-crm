import { NextRequest, NextResponse } from 'next/server'
import { requireAuth } from '@/lib/auth-helper'
import Anthropic from '@anthropic-ai/sdk'

export const runtime = 'nodejs'
export const maxDuration = 60

const DISCLAIMER = 'DISCLAIMER: This document was generated by Saguaro Construction Intelligence Platform. This document does not constitute legal advice. Verify compliance with current state statutes and consult a licensed state construction attorney before relying on this document for legal purposes.'

export async function POST(req: NextRequest) {
  const auth = await requireAuth()
  if (auth instanceof NextResponse) return auth
  const { supabase, tenantId } = auth

  const { projectId, description, relatedRfiId } = await req.json()
  if (!projectId || !description) {
    return NextResponse.json({ error: 'projectId and description required' }, { status: 400 })
  }

  const [{ data: project }, { data: gc }, { data: primeContract }, { count: existingCOs }] = await Promise.all([
    supabase.from('projects').select('name,address,city,state,building_type,contract_value,start_date,end_date,owner_name').eq('id', projectId).single(),
    supabase.from('tenant_settings').select('company_name,default_retainage_pct,default_payment_terms,signature_name,signature_title,license_number,company_address,company_city,company_state,company_zip').eq('tenant_id', tenantId).maybeSingle(),
    supabase.from('prime_contracts').select('*').eq('project_id', projectId).eq('tenant_id', tenantId).maybeSingle(),
    supabase.from('change_orders').select('*', { count: 'exact', head: true }).eq('project_id', projectId).eq('tenant_id', tenantId),
  ])

  const nextCoNumber = (existingCOs || 0) + 1
  const today = new Date().toLocaleDateString('en-US', { year: 'numeric', month: 'long', day: 'numeric' })

  const client = new Anthropic()
  const msg = await client.messages.create({
    model: 'claude-sonnet-4-20250514',
    max_tokens: 2500,
    system: `You are a construction change order expert with 20 years experience.
Generate complete, professional change order documentation.
Return ONLY valid JSON, no markdown.`,
    messages: [{
      role: 'user',
      content: `Draft a complete change order for this construction change.

PROJECT: ${project?.name || 'Project'}
BUILDING TYPE: ${project?.building_type || 'Commercial'}
LOCATION: ${project?.city || ''}, ${project?.state || ''}
CONTRACT VALUE: $${Number(project?.contract_value || 0).toLocaleString()}
RETAINAGE: ${Number(gc?.default_retainage_pct || 10)}%

CHANGE DESCRIPTION FROM GC:
"${description}"

Generate a complete change order. Return this JSON:
{
  "title": "brief professional title for this CO",
  "co_number": ${nextCoNumber},
  "change_type": "additive|deductive|no_cost",
  "reason": "owner_requested|unforeseen_conditions|design_change|code_requirement|value_engineering|omission",
  "scope_of_change": "detailed 2-3 paragraph professional scope narrative explaining what is included, the technical details, and why it's a legitimate change to the contract",
  "work_included": ["bullet 1", "bullet 2", "bullet 3"],
  "work_excluded": ["item 1 explicitly excluded", "item 2 excluded"],
  "schedule_impact_days": number (0 if no impact, realistic number if there is),
  "materials_amount": number,
  "labor_amount": number,
  "equipment_amount": number,
  "subtrade_amount": number,
  "subtotal": number,
  "overhead_pct": 15,
  "overhead_amount": number,
  "profit_pct": 10,
  "profit_amount": number,
  "total_amount": number (subtotal + overhead + profit),
  "line_items": [
    {"description": "string", "category": "material|labor|equipment|subtrade", "quantity": number, "unit": "string", "unit_cost": number, "amount": number}
  ],
  "billable_to": "owner|subcontractor|insurance",
  "contract_clause": "cite the specific contract clause or section that supports this change order (e.g. Article 7.1 - Changes in the Work)",
  "ai_pricing_source": "RSMeans|historical_similar_projects|industry_standard"
}`,
    }],
  })

  const raw = msg.content[0]?.type === 'text' ? msg.content[0].text.replace(/```json\n?|\n?```/g, '').trim() : '{}'
  let draft: Record<string, unknown> = {}
  try { draft = JSON.parse(raw) } catch { /* empty */ }

  const subtotal = Number(draft.subtotal) || (Number(draft.materials_amount || 0) + Number(draft.labor_amount || 0) + Number(draft.equipment_amount || 0) + Number(draft.subtrade_amount || 0))
  const overheadAmt = subtotal * 0.15
  const profitAmt = (subtotal + overheadAmt) * 0.10
  const totalAmount = subtotal + overheadAmt + profitAmt

  const gcName = gc?.company_name || 'General Contractor'
  const ownerName = primeContract?.owner_name || project?.owner_name || 'Owner'

  const htmlContent = `<!DOCTYPE html>
<html>
<head>
  <meta charset="utf-8">
  <title>Change Order #${nextCoNumber}</title>
  <style>
    @page { size: letter portrait; margin: 0.75in; }
    @media print { .no-print { display:none!important; } }
    * { box-sizing:border-box; margin:0; padding:0; }
    body { font-family: Arial, sans-serif; font-size: 10pt; color: #1a1a1a; }
    .header { background: linear-gradient(135deg, #1a1a2e, #16213e); color: #fff; padding: 16px 22px; display: flex; justify-content: space-between; }
    .company { font-size: 14pt; font-weight: 900; color: #D4A017; }
    .gold-bar { height: 4px; background: linear-gradient(90deg,#D4A017,#F0C040); }
    .title-bar { background: #f7f8fa; border-bottom: 2px solid #D4A017; padding: 10px 22px; }
    .content { padding: 16px 22px; }
    table.info { width: 100%; border-collapse: collapse; margin-bottom: 14px; font-size: 9.5pt; }
    table.info td { padding: 4px 8px; border: 1px solid #ddd; }
    table.info td:first-child { font-weight: 700; background: #f8f8f8; width: 150px; }
    table.pricing { width: 100%; border-collapse: collapse; margin: 12px 0; font-size: 9.5pt; }
    table.pricing th { background: #1a1a2e; color: #fff; padding: 5px 8px; text-align: left; }
    table.pricing td { padding: 4px 8px; border-bottom: 1px solid #eee; }
    table.pricing tr.subtotal td { background: #f5f5f5; font-weight: 700; }
    table.pricing tr.total td { background: #1a1a2e; color: #D4A017; font-weight: 900; font-size: 11pt; }
    .sig-grid { display: grid; grid-template-columns: 1fr 1fr 1fr; gap: 16px; margin-top: 20px; }
    .sig-box { border: 1px solid #ddd; padding: 10px; }
    .sig-line { border-bottom: 1px solid #333; margin: 10px 0 3px; min-height: 28px; }
    .print-btn { position: fixed; top: 10px; right: 10px; background: #D4A017; color: #000; border: none; padding: 7px 16px; font-weight: 700; cursor: pointer; border-radius: 6px; }
    h4 { font-size: 10pt; font-weight: 900; color: #1a1a2e; margin: 12px 0 6px; text-transform: uppercase; letter-spacing: .04em; border-bottom: 1px solid #ddd; padding-bottom: 3px; }
  </style>
</head>
<body>
  <button class="print-btn no-print" onclick="window.print()">🖨️ Print / Save PDF</button>
  <div class="header">
    <div><div class="company">${gcName}</div><div style="font-size:8pt;color:rgba(255,255,255,.7);margin-top:3px">${project?.name || 'Project'}</div></div>
    <div style="text-align:right;font-size:8pt;color:rgba(255,255,255,.7)">CHANGE ORDER<br>${today}</div>
  </div>
  <div class="gold-bar"></div>
  <div class="title-bar">
    <div style="font-size:13pt;font-weight:900;color:#1a1a2e;text-transform:uppercase">
      Change Order No. ${nextCoNumber} — ${String(draft.title || 'Change Order')}
    </div>
    <div style="font-size:9pt;color:#666;margin-top:3px">
      ${String(draft.change_type || 'additive')} · Billable to: ${String(draft.billable_to || 'owner')} · ${today}
    </div>
  </div>
  <div class="content">
    <table class="info">
      <tr><td>Project</td><td>${project?.name || ''}</td><td>Owner</td><td>${ownerName}</td></tr>
      <tr><td>Contractor</td><td>${gcName}</td><td>CO Number</td><td>${nextCoNumber}</td></tr>
      <tr><td>Date</td><td>${today}</td><td>Schedule Impact</td><td>${Number(draft.schedule_impact_days || 0) > 0 ? Number(draft.schedule_impact_days) + ' calendar days' : 'No impact'}</td></tr>
      <tr><td>Reason</td><td>${String(draft.reason || '').replace(/_/g, ' ')}</td><td>Contract Ref.</td><td>${String(draft.contract_clause || '')}</td></tr>
    </table>
    <h4>Scope of Change</h4>
    <div style="font-size:9.5pt;line-height:1.65;white-space:pre-wrap">${String(draft.scope_of_change || description)}</div>
    ${Array.isArray(draft.work_included) && (draft.work_included as string[]).length > 0 ? `
    <h4>Work Included</h4>
    <ul style="font-size:9.5pt;line-height:1.7;padding-left:18px">${(draft.work_included as string[]).map(w => `<li>${w}</li>`).join('')}</ul>` : ''}
    ${Array.isArray(draft.work_excluded) && (draft.work_excluded as string[]).length > 0 ? `
    <h4>Work Excluded</h4>
    <ul style="font-size:9.5pt;line-height:1.7;padding-left:18px;color:#666">${(draft.work_excluded as string[]).map(w => `<li>${w}</li>`).join('')}</ul>` : ''}
    <h4>Cost Breakdown</h4>
    <table class="pricing">
      <thead><tr><th>Description</th><th>Category</th><th style="text-align:right">Amount</th></tr></thead>
      <tbody>
        ${Number(draft.materials_amount || 0) > 0 ? `<tr><td>Materials</td><td>Materials</td><td style="text-align:right">$${Number(draft.materials_amount || 0).toLocaleString()}</td></tr>` : ''}
        ${Number(draft.labor_amount || 0) > 0 ? `<tr><td>Labor</td><td>Labor</td><td style="text-align:right">$${Number(draft.labor_amount || 0).toLocaleString()}</td></tr>` : ''}
        ${Number(draft.equipment_amount || 0) > 0 ? `<tr><td>Equipment</td><td>Equipment</td><td style="text-align:right">$${Number(draft.equipment_amount || 0).toLocaleString()}</td></tr>` : ''}
        ${Number(draft.subtrade_amount || 0) > 0 ? `<tr><td>Subtrade Work</td><td>Subtrade</td><td style="text-align:right">$${Number(draft.subtrade_amount || 0).toLocaleString()}</td></tr>` : ''}
        <tr class="subtotal"><td colspan="2">Subtotal</td><td style="text-align:right">$${subtotal.toLocaleString()}</td></tr>
        <tr><td>Overhead (15%)</td><td></td><td style="text-align:right">$${Math.round(overheadAmt).toLocaleString()}</td></tr>
        <tr><td>Profit (10%)</td><td></td><td style="text-align:right">$${Math.round(profitAmt).toLocaleString()}</td></tr>
        <tr class="total"><td colspan="2">TOTAL CHANGE ORDER AMOUNT</td><td style="text-align:right">$${Math.round(totalAmount).toLocaleString()}</td></tr>
      </tbody>
    </table>
    <h4>Signatures</h4>
    <div class="sig-grid">
      <div class="sig-box"><strong>CONTRACTOR</strong><br>${gcName}<div class="sig-line">&nbsp;</div><div style="font-size:7.5pt;color:#666">Authorized Signature / Date</div></div>
      <div class="sig-box"><strong>OWNER</strong><br>${ownerName}<div class="sig-line">&nbsp;</div><div style="font-size:7.5pt;color:#666">Authorized Signature / Date</div></div>
      <div class="sig-box"><strong>ARCHITECT/ENGINEER</strong><br>&nbsp;<div class="sig-line">&nbsp;</div><div style="font-size:7.5pt;color:#666">Authorized Signature / Date</div></div>
    </div>
    <div style="margin-top:16px;font-size:7.5pt;color:#aaa">${DISCLAIMER}</div>
  </div>
</body>
</html>`

  const lineItems = Array.isArray(draft.line_items) ? draft.line_items as Array<Record<string, unknown>> : []
  const { data: co, error: coErr } = await supabase.from('change_orders').insert({
    tenant_id: tenantId,
    project_id: projectId,
    title: String(draft.title || description.slice(0, 100)),
    co_number: nextCoNumber,
    description,
    scope_of_change: String(draft.scope_of_change || ''),
    work_included: Array.isArray(draft.work_included) ? draft.work_included : [],
    work_excluded: Array.isArray(draft.work_excluded) ? draft.work_excluded : [],
    change_type: String(draft.change_type || 'additive'),
    reason: String(draft.reason || ''),
    amount: Math.round(totalAmount),
    materials_amount: Number(draft.materials_amount || 0),
    labor_amount: Number(draft.labor_amount || 0),
    equipment_amount: Number(draft.equipment_amount || 0),
    subtrade_amount: Number(draft.subtrade_amount || 0),
    overhead_amount: Math.round(overheadAmt),
    profit_amount: Math.round(profitAmt),
    markup_overhead_pct: 15,
    markup_profit_pct: 10,
    schedule_impact_days: Number(draft.schedule_impact_days || 0),
    billable_to: String(draft.billable_to || 'owner'),
    status: 'pending',
    ai_generated: true,
    ai_draft_narrative: String(draft.scope_of_change || ''),
    ai_pricing_source: String(draft.ai_pricing_source || 'industry_standard'),
    html_content: htmlContent,
    related_rfi_id: relatedRfiId || null,
    original_co_amount: Math.round(totalAmount),
  }).select('id').single()

  if (coErr) return NextResponse.json({ error: coErr.message }, { status: 500 })

  if (lineItems.length > 0 && co?.id) {
    await supabase.from('change_order_line_items').insert(
      lineItems.map((item, i) => ({
        tenant_id: tenantId,
        change_order_id: co.id,
        description: String(item.description || `Line ${i + 1}`),
        category: String(item.category || 'labor'),
        quantity: Number(item.quantity || 1),
        unit: String(item.unit || 'LS'),
        unit_cost: Number(item.unit_cost || 0),
        amount: Number(item.amount || 0),
        markup_pct: 0,
        total: Number(item.amount || 0),
        sort_order: i,
      })),
    )
  }

  await supabase.from('generated_documents').insert({
    tenant_id: tenantId,
    project_id: projectId,
    doc_type: 'change_order',
    status: 'generated',
    source_type: 'change_order',
    source_id: co?.id,
    data_snapshot: { co_number: nextCoNumber, amount: totalAmount, title: draft.title },
  })

  return NextResponse.json({
    success: true,
    coId: co?.id,
    coNumber: nextCoNumber,
    totalAmount: Math.round(totalAmount),
    scheduleImpactDays: Number(draft.schedule_impact_days || 0),
    changeType: String(draft.change_type || 'additive'),
    title: String(draft.title || description.slice(0, 100)),
    html_content: htmlContent,
    draft,
  })
}
