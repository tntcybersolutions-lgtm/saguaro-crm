import { NextRequest, NextResponse } from 'next/server'
import { requireAuth } from '@/lib/auth-helper'
import Anthropic from '@anthropic-ai/sdk'

export const runtime = 'nodejs'
export const maxDuration = 60

const DISCLAIMER = 'DISCLAIMER: This document was generated by Saguaro Construction Intelligence Platform. This document does not constitute legal advice. Verify compliance with current state statutes and consult a licensed state construction attorney before relying on this document for legal purposes.'

export async function POST(req: NextRequest) {
  const auth = await requireAuth()
  if (auth instanceof NextResponse) return auth
  const { supabase, tenantId } = auth

  const { projectId, description } = await req.json()
  if (!projectId || !description) {
    return NextResponse.json({ error: 'projectId and description required' }, { status: 400 })
  }

  const descStr = String(description)

  const [{ data: project }, { data: gc }, { count: rfiCount }] = await Promise.all([
    supabase
      .from('projects')
      .select('name, building_type, architect_name, architect_email, engineer_name, owner_name')
      .eq('id', projectId)
      .single(),
    supabase.from('tenant_settings').select('company_name, signature_name').eq('tenant_id', tenantId).maybeSingle(),
    supabase
      .from('rfis')
      .select('*', { count: 'exact', head: true })
      .eq('project_id', projectId)
      .eq('tenant_id', tenantId),
  ])

  const nextRfiNumber = `RFI-${String((rfiCount || 0) + 1).padStart(3, '0')}`
  const today = new Date().toISOString().split('T')[0]
  const dueDate = new Date(Date.now() + 7 * 24 * 60 * 60 * 1000).toISOString().split('T')[0]
  const gcName = gc?.company_name || 'General Contractor'

  let draft: Record<string, unknown> = {}
  try {
    const client = new Anthropic()
    const msg = await client.messages.create({
      model: 'claude-sonnet-4-20250514',
      max_tokens: 1500,
      system:
        'You are a construction RFI expert. Write formal, professional RFI documents. Return ONLY valid JSON, no markdown.',
      messages: [{
        role: 'user',
        content: `Draft a complete Request for Information (RFI) for this construction question.

PROJECT: ${project?.name || 'Project'}
BUILDING TYPE: ${project?.building_type || 'Commercial'}
CONTRACTOR: ${gcName}
SUBMITTED BY: ${gc?.signature_name || 'Project Manager'}
ARCHITECT: ${project?.architect_name || 'Architect of Record'}
DATE: ${today}
RFI NO: ${nextRfiNumber}

QUESTION/ISSUE FROM GC:
"${descStr}"

Return this JSON:
{
  "subject": "brief professional RFI title (max 80 chars)",
  "question": "full formal question text (2-3 paragraphs, professional language, reference to contract/specs/drawings where appropriate)",
  "spec_section": "most likely spec section reference (e.g. '09 00 00 — Finishes' or '23 00 00 — HVAC')",
  "drawing_reference": "likely drawing reference (e.g. 'Sheet A-101, Detail 3' or 'M-201')",
  "suggested_answer": "a suggested potential answer or resolution that the GC is proposing",
  "ball_in_court": "architect|engineer|owner|gc",
  "assigned_to": "${project?.architect_name || 'Architect'}",
  "assigned_to_email": "${project?.architect_email || ''}",
  "priority": "normal|high|urgent",
  "schedule_impact": "brief description of schedule impact if not answered in time, or 'None'",
  "schedule_impact_days": 0,
  "cost_impact": 0,
  "contract_reference": "contract article or section that applies"
}`,
      }],
    })

    const raw = msg.content[0]?.type === 'text'
      ? msg.content[0].text.replace(/```json\n?|\n?```/g, '').trim()
      : '{}'
    draft = JSON.parse(raw)
  } catch {
    draft = {}
  }

  const subject = String(draft.subject || descStr).slice(0, 200)
  const question = String(draft.question || descStr)
  const todayFmt = new Date().toLocaleDateString('en-US', { year: 'numeric', month: 'long', day: 'numeric' })
  const priority = String(draft.priority || 'normal')
  const assignedTo = String(draft.assigned_to || project?.architect_name || 'Architect')

  const priorityBg = priority === 'urgent' ? 'rgba(248,81,73,.15)' : priority === 'high' ? 'rgba(240,180,41,.15)' : 'rgba(96,165,250,.12)'
  const priorityColor = priority === 'urgent' ? '#F85149' : priority === 'high' ? '#F0B429' : '#60a5fa'

  const htmlContent = `<!DOCTYPE html>
<html>
<head>
  <meta charset="utf-8"><title>RFI ${nextRfiNumber}</title>
  <style>
    @page { size: letter portrait; margin: 0.75in; }
    @media print { .no-print { display:none!important; } }
    * { box-sizing:border-box; margin:0; padding:0; }
    body { font-family: Arial, sans-serif; font-size: 10pt; color: #1a1a1a; background: #fff; line-height: 1.6; }
    .header { background: linear-gradient(135deg,#1a1a2e,#16213e); color: #fff; padding: 14px 22px; display: flex; justify-content: space-between; }
    .company-name { font-size: 13pt; font-weight: 900; color: #D4A017; }
    .gold-bar { height: 4px; background: linear-gradient(90deg,#D4A017,#F0C040); }
    .title-bar { background: #f7f8fa; border-bottom: 2px solid #D4A017; padding: 10px 22px; display: flex; justify-content: space-between; align-items: center; }
    .content { padding: 16px 22px; }
    table.info { width: 100%; border-collapse: collapse; margin-bottom: 14px; font-size: 9.5pt; }
    table.info td { padding: 4px 8px; border: 1px solid #ddd; }
    table.info td:first-child { font-weight: 700; background: #f8f8f8; width: 130px; }
    h4 { font-size: 10pt; font-weight: 900; color: #1a1a2e; margin: 14px 0 6px; text-transform: uppercase; letter-spacing: .04em; border-bottom: 1px solid #ddd; padding-bottom: 3px; }
    .response-box { background: #f9fafb; border: 2px dashed #D4A017; padding: 14px; margin: 14px 0; min-height: 80px; }
    .print-btn { position: fixed; top: 10px; right: 10px; background: #D4A017; color: #000; border: none; padding: 7px 16px; font-weight: 700; cursor: pointer; border-radius: 6px; }
    .badge { display: inline-block; padding: 2px 10px; border-radius: 12px; font-size: 9pt; font-weight: 700; }
  </style>
</head>
<body>
  <button class="print-btn no-print" onclick="window.print()">🖨️ Print / Save PDF</button>
  <div class="header">
    <div><div class="company-name">${gcName}</div></div>
    <div style="text-align:right;font-size:9pt;color:rgba(255,255,255,.8)">REQUEST FOR INFORMATION<br>${todayFmt}</div>
  </div>
  <div class="gold-bar"></div>
  <div class="title-bar">
    <div style="font-size:13pt;font-weight:900;color:#1a1a2e">${nextRfiNumber} — ${subject}</div>
    <span class="badge" style="background:${priorityBg};color:${priorityColor}">${priority.toUpperCase()}</span>
  </div>
  <div class="content">
    <table class="info">
      <tr><td>RFI Number</td><td>${nextRfiNumber}</td><td>Date</td><td>${todayFmt}</td></tr>
      <tr><td>Project</td><td>${project?.name || '—'}</td><td>Due Date</td><td>${dueDate}</td></tr>
      <tr><td>From</td><td>${gcName}</td><td>Assigned To</td><td>${assignedTo}</td></tr>
      <tr><td>Spec Section</td><td>${String(draft.spec_section || '—')}</td><td>Drawing Ref.</td><td>${String(draft.drawing_reference || '—')}</td></tr>
      <tr><td>Schedule Impact</td><td>${Number(draft.schedule_impact_days || 0) > 0 ? `${draft.schedule_impact_days} days` : 'None'}</td><td>Cost Impact</td><td>${Number(draft.cost_impact || 0) > 0 ? `$${Number(draft.cost_impact).toLocaleString()}` : 'None'}</td></tr>
    </table>
    <h4>Question / Request for Clarification</h4>
    <div style="font-size:9.5pt;line-height:1.7;white-space:pre-wrap">${question}</div>
    ${draft.suggested_answer ? `
    <h4>Contractor's Proposed Resolution</h4>
    <div style="font-size:9.5pt;line-height:1.7;background:#f0fdf4;padding:12px;border-left:4px solid #3DD68C">${String(draft.suggested_answer)}</div>` : ''}
    <h4>Architect/Engineer Response</h4>
    <div class="response-box">
      <div style="font-size:9pt;color:#888;font-style:italic">Response to be provided by ${assignedTo} within 7 business days</div>
    </div>
    <div style="display:grid;grid-template-columns:1fr 1fr;gap:20px;margin-top:16px">
      <div>
        <div style="font-size:9pt;font-weight:700;margin-bottom:6px">SUBMITTED BY — ${gcName}</div>
        <div style="border-bottom:1px solid #333;margin:10px 0 3px;min-height:24px"></div>
        <div style="font-size:8pt;color:#666">Signature / Date</div>
        <div style="margin-top:4px">${gc?.signature_name || '—'}</div>
      </div>
      <div>
        <div style="font-size:9pt;font-weight:700;margin-bottom:6px">RESPONDED BY — ${assignedTo}</div>
        <div style="border-bottom:1px solid #333;margin:10px 0 3px;min-height:24px"></div>
        <div style="font-size:8pt;color:#666">Signature / Date</div>
      </div>
    </div>
    <div style="margin-top:14px;font-size:7.5pt;color:#aaa">${DISCLAIMER}</div>
  </div>
</body>
</html>`

  const { data: rfi, error: rfiErr } = await supabase
    .from('rfis')
    .insert({
      tenant_id: tenantId,
      project_id: projectId,
      rfi_number: nextRfiNumber,
      subject,
      question,
      spec_section: String(draft.spec_section || ''),
      drawing_reference: String(draft.drawing_reference || ''),
      due_date: dueDate,
      status: 'open',
      priority,
      ball_in_court: String(draft.ball_in_court || 'architect'),
      submitted_by: gc?.signature_name || gcName,
      submitted_at: new Date().toISOString(),
      days_to_respond: 7,
      schedule_impact_days: Number(draft.schedule_impact_days || 0),
      cost_impact: Number(draft.cost_impact || 0),
      ai_suggested: true,
      ai_drafted_at: new Date().toISOString(),
      draft_answer: String(draft.suggested_answer || ''),
      ai_draft_question: question,
      html_content: htmlContent,
      assigned_to_name: assignedTo,
      assigned_to_email: String(draft.assigned_to_email || project?.architect_email || ''),
      sage_analysis: {
        description: descStr,
        contract_reference: String(draft.contract_reference || ''),
        priority_reason: priority,
      },
      is_overdue: false,
    })
    .select('id')
    .single()

  if (rfiErr) return NextResponse.json({ error: rfiErr.message }, { status: 500 })

  await supabase.from('generated_documents').insert({
    tenant_id: tenantId,
    project_id: projectId,
    doc_type: 'rfi',
    status: 'generated',
    source_type: 'rfi',
    source_id: rfi?.id,
    data_snapshot: { rfi_number: nextRfiNumber, subject, priority },
  })

  return NextResponse.json({ success: true, rfiId: rfi?.id, rfiNumber: nextRfiNumber, draft })
}

export async function GET(req: NextRequest) {
  const auth = await requireAuth()
  if (auth instanceof NextResponse) return auth
  const { supabase, tenantId } = auth
  const rfiId = req.nextUrl.searchParams.get('id')
  if (!rfiId) return NextResponse.json({ error: 'id required' }, { status: 400 })
  const { data: rfi } = await supabase
    .from('rfis')
    .select('html_content')
    .eq('id', rfiId)
    .eq('tenant_id', tenantId)
    .single()
  if (!rfi?.html_content) return NextResponse.json({ error: 'Not generated' }, { status: 404 })
  return new Response(rfi.html_content, { headers: { 'Content-Type': 'text/html; charset=utf-8' } })
}
