    const total = prev + curr + stored
    const pct = sv > 0 ? Math.round((total / sv) * 100) : 0
    const bal = sv - total
    const ret = total * (retainagePct / 100)
    const bg = i % 2 === 0 ? '#fff' : '#f9f9f9'
