  const retainagePct = Number(app.retainage_percent || primeContract?.retainage_pct || 10)
  const retainageThisPeriod = (thisPeriod + storedMaterials) * (retainagePct / 100)
  const retainagePrevious = prevCompleted * (retainagePct / 100)
  const totalRetainage = retainageThisPeriod + retainagePrevious
