export async function GET(
  req: NextRequest,
  { params }: { params: Promise<{ id: string }> },
) {
  const auth = await requireAuth()
  if (auth instanceof NextResponse) return auth
  const { supabase, tenantId } = auth
  const { id } = await params
  const doc = req.nextUrl.searchParams.get('doc') || 'g702'
  const { data: app } = await supabase
    .from('pay_applications')
    .select('g702_html,g703_html')
    .eq('id', id)
    .eq('tenant_id', tenantId)
    .single()
  if (!app) return NextResponse.json({ error: 'Not found' }, { status: 404 })
  const html = doc === 'g703' ? app.g703_html : app.g702_html
  if (!html) return NextResponse.json({ error: 'Not generated yet. POST to generate.' }, { status: 404 })
  return new Response(html, { headers: { 'Content-Type': 'text/html; charset=utf-8' } })
}
