import { NextRequest, NextResponse } from 'next/server'
import { requireAuth } from '@/lib/auth-helper'
import Anthropic from '@anthropic-ai/sdk'

export const runtime = 'nodejs'
export const maxDuration = 60

const DISCLAIMER = 'DISCLAIMER: This document was generated by Saguaro Construction Intelligence Platform. This document does not constitute legal advice. Verify compliance with current state statutes and consult a licensed state construction attorney before relying on this document for legal purposes.'

const CATEGORY_LABELS: Record<string, string> = {
  om_manuals: 'O&M Manuals',
  warranties: 'Warranties',
  as_builts: 'As-Built Drawings',
  certificates: 'Certificates & Inspections',
  lien_waivers: 'Lien Waivers',
  attic_stock: 'Spare Parts & Attic Stock',
  training: 'Owner Training',
  final_submissions: 'Final Submissions',
  other: 'Other',
}

interface CloseoutItem {
  id: string
  category: string | null
  title: string
  required_from: string | null
  status: string | null
  received_at: string | null
  notes: string | null
}

export async function POST(req: NextRequest) {
  const auth = await requireAuth()
  if (auth instanceof NextResponse) return auth
  const { supabase, tenantId } = auth
  const { projectId } = await req.json()
  if (!projectId) return NextResponse.json({ error: 'projectId required' }, { status: 400 })

  const [projectRes, gcRes, itemsRes, pkgRes] = await Promise.all([
    supabase.from('projects').select('name, address, city, state, owner_name, end_date').eq('id', projectId).single(),
    supabase.from('tenant_settings').select('company_name, signature_name, signature_title, company_phone, company_email').eq('tenant_id', tenantId).maybeSingle(),
    supabase.from('closeout_items').select('id, category, title, required_from, status, received_at, notes').eq('project_id', projectId).eq('tenant_id', tenantId).order('category'),
    supabase.from('closeout_packages').select('*').eq('project_id', projectId).eq('tenant_id', tenantId).eq('is_active', true).maybeSingle(),
  ])

  const project = projectRes.data
  const gc = gcRes.data
  const items = (itemsRes.data || []) as CloseoutItem[]

  const received = items.filter((i) => i.status === 'received' || i.status === 'complete').length
  const total = items.length
  const pct = total > 0 ? Math.round((received / total) * 100) : 0
  const today = new Date().toLocaleDateString('en-US', { year: 'numeric', month: 'long', day: 'numeric' })
  const gcName = gc?.company_name || 'General Contractor'

  const grouped: Record<string, CloseoutItem[]> = {}
  for (const item of items) {
    const cat = item.category || 'other'
    if (!grouped[cat]) grouped[cat] = []
    grouped[cat].push(item)
  }

  let sageSummary = ''
  try {
    const client = new Anthropic()
    const summaryMsg = await client.messages.create({
      model: 'claude-sonnet-4-20250514',
      max_tokens: 400,
      messages: [{
        role: 'user',
        content: `Write a 2-paragraph professional closeout transmittal summary for ${project?.name || 'this project'}. ${received} of ${total} items received (${pct}% complete). Contractor: ${gcName}. Date: ${today}. Be professional and formal.`,
      }],
    })
    sageSummary = summaryMsg.content[0]?.type === 'text' ? summaryMsg.content[0].text : ''
  } catch {
    sageSummary = `Project closeout for ${project?.name || 'this project'} is ${pct}% complete with ${received} of ${total} items received.`
  }

  const categoryRows = Object.entries(grouped)
    .map(([cat, catItems]) => {
      const catReceived = catItems.filter((i) => i.status === 'received' || i.status === 'complete').length
      const catTotal = catItems.length
      const rows = catItems
        .map((item) => {
          const status = item.status || 'pending'
          const statusColor =
            status === 'received' || status === 'complete' ? '#3DD68C' : status === 'pending' ? '#F85149' : '#F0B429'
          return `<tr>
        <td style="font-size:9pt;padding:4px 8px">${item.title}</td>
        <td style="font-size:9pt;padding:4px 8px;color:#666">${item.required_from || '—'}</td>
        <td style="text-align:center;padding:4px 8px"><span style="font-size:9pt;font-weight:700;color:${statusColor}">${status}</span></td>
        <td style="font-size:9pt;padding:4px 8px;color:#666">${item.received_at ? new Date(item.received_at).toLocaleDateString() : '—'}</td>
        <td style="font-size:9pt;padding:4px 8px">${item.notes || '—'}</td>
      </tr>`
        })
        .join('')
      return `
      <tr><td colspan="5" style="background:#1a1a2e;color:#D4A017;font-weight:900;font-size:9.5pt;padding:6px 8px;text-transform:uppercase">
        ${CATEGORY_LABELS[cat] || cat} (${catReceived}/${catTotal} received)
      </td></tr>
      ${rows}`
    })
    .join('')

  const htmlContent = `<!DOCTYPE html>
<html>
<head>
  <meta charset="utf-8">
  <title>Project Closeout Package — ${project?.name || 'Project'}</title>
  <style>
    @page { size: letter portrait; margin: 0.75in; }
    @media print { .no-print { display:none!important; } }
    * { box-sizing:border-box; margin:0; padding:0; }
    body { font-family: Arial, sans-serif; font-size: 10pt; color: #1a1a1a; background: #fff; }
    .header { background: linear-gradient(135deg,#1a1a2e,#16213e); color: #fff; padding: 16px 22px; display: flex; justify-content: space-between; }
    .company-name { font-size: 14pt; font-weight: 900; color: #D4A017; }
    .gold-bar { height: 4px; background: linear-gradient(90deg,#D4A017,#F0C040); }
    .progress-bar { height: 8px; background: #e5e7eb; border-radius: 4px; overflow: hidden; margin: 8px 0; }
    .progress-fill { height: 100%; background: linear-gradient(90deg,#3DD68C,#D4A017); border-radius: 4px; }
    table { width: 100%; border-collapse: collapse; }
    th { background: #374151; color: #fff; padding: 6px 8px; text-align: left; font-size: 9pt; }
    td { border-bottom: 1px solid #e5e7eb; vertical-align: top; }
    .print-btn { position: fixed; top: 10px; right: 10px; background: #D4A017; color: #000; border: none; padding: 7px 16px; font-weight: 700; cursor: pointer; border-radius: 6px; }
  </style>
</head>
<body>
  <button class="print-btn no-print" onclick="window.print()">🖨️ Print / Save PDF</button>
  <div class="header">
    <div><div class="company-name">${gcName}</div><div style="font-size:8pt;color:rgba(255,255,255,.65);margin-top:4px">${project?.name || 'Project'}</div></div>
    <div style="text-align:right;font-size:8pt;color:rgba(255,255,255,.7)">CLOSEOUT PACKAGE TRANSMITTAL<br>${today}</div>
  </div>
  <div class="gold-bar"></div>
  <div style="padding:18px 22px">
    <div style="display:grid;grid-template-columns:1fr 1fr;gap:20px;margin-bottom:20px">
      <div>
        <div style="font-size:11pt;font-weight:900;margin-bottom:8px">Closeout Status</div>
        <div class="progress-bar"><div class="progress-fill" style="width:${pct}%"></div></div>
        <div style="font-size:24pt;font-weight:900;color:${pct === 100 ? '#3DD68C' : '#D4A017'}">${pct}%</div>
        <div style="font-size:9pt;color:#666">${received} of ${total} items received</div>
      </div>
      <div>
        <div style="font-size:9.5pt;line-height:1.6">
          <strong>Project:</strong> ${project?.name || '—'}<br>
          <strong>Address:</strong> ${[project?.address, project?.city ? `${project.city}, ${project.state}` : ''].filter(Boolean).join(', ')}<br>
          <strong>Owner:</strong> ${project?.owner_name || '—'}<br>
          <strong>Completion Date:</strong> ${project?.end_date || '—'}<br>
          <strong>Contractor:</strong> ${gcName}
        </div>
      </div>
    </div>
    <div style="margin-bottom:16px;padding:14px;background:#f9fafb;border-left:4px solid #D4A017;font-size:9.5pt;line-height:1.7;white-space:pre-wrap">${sageSummary}</div>
    <table>
      <thead>
        <tr>
          <th>Item</th><th>Required From</th><th style="width:80px;text-align:center">Status</th>
          <th style="width:90px">Received Date</th><th>Notes</th>
        </tr>
      </thead>
      <tbody>${categoryRows}</tbody>
    </table>
    <div style="margin-top:24px;display:grid;grid-template-columns:1fr 1fr;gap:28px">
      <div style="border:1px solid #ddd;padding:14px">
        <strong>CONTRACTOR:</strong> ${gcName}<br>
        <div style="border-bottom:1px solid #333;margin:12px 0 3px;min-height:28px"></div>
        <div style="font-size:8pt;color:#666">Authorized Signature / Date</div>
        <div style="margin-top:8px">${gc?.signature_name || '—'}, ${gc?.signature_title || '—'}</div>
      </div>
      <div style="border:1px solid #ddd;padding:14px">
        <strong>OWNER:</strong> ${project?.owner_name || '—'}<br>
        <div style="border-bottom:1px solid #333;margin:12px 0 3px;min-height:28px"></div>
        <div style="font-size:8pt;color:#666">Owner Signature / Date</div>
      </div>
    </div>
    <div style="margin-top:14px;font-size:7.5pt;color:#aaa">${DISCLAIMER}</div>
  </div>
</body>
</html>`

  // Upsert or update closeout_packages
  if (pkgRes.data?.id) {
    await supabase
      .from('closeout_packages')
      .update({
        pct_complete: pct,
        sage_summary: sageSummary,
        html_content: htmlContent,
        status: pct === 100 ? 'complete' : 'active',
        assembled_at: new Date().toISOString(),
        updated_at: new Date().toISOString(),
      })
      .eq('id', pkgRes.data.id)
      .eq('tenant_id', tenantId)
  } else {
    await supabase
      .from('closeout_packages')
      .insert({
        tenant_id: tenantId,
        project_id: projectId,
        package_name: `${project?.name || 'Project'} — Closeout Package`,
        status: pct === 100 ? 'complete' : 'active',
        pct_complete: pct,
        sage_summary: sageSummary,
        html_content: htmlContent,
        assembled_at: new Date().toISOString(),
        is_active: true,
      })
  }

  await supabase.from('generated_documents').insert({
    tenant_id: tenantId,
    project_id: projectId,
    doc_type: 'closeout_package',
    status: 'generated',
    source_type: 'closeout_package',
    source_id: pkgRes.data?.id || null,
    data_snapshot: { pct_complete: pct, received, total },
  })

  return NextResponse.json({ success: true, pct, received, total, htmlAvailable: true })
}

export async function GET(req: NextRequest) {
  const auth = await requireAuth()
  if (auth instanceof NextResponse) return auth
  const { supabase, tenantId } = auth
  const projectId = req.nextUrl.searchParams.get('projectId')
  if (!projectId) return NextResponse.json({ error: 'projectId required' }, { status: 400 })
  const { data: pkg } = await supabase
    .from('closeout_packages')
    .select('html_content')
    .eq('project_id', projectId)
    .eq('tenant_id', tenantId)
    .eq('is_active', true)
    .maybeSingle()
  if (!pkg?.html_content) return NextResponse.json({ error: 'Not yet assembled' }, { status: 404 })
  return new Response(pkg.html_content, { headers: { 'Content-Type': 'text/html; charset=utf-8' } })
}
